drop policy if exists "profiles read authenticated" on public.profiles;
create policy "profiles read authenticated" on public.profiles for select to authenticated using (true);
drop policy if exists "profiles update own" on public.profiles;
create policy "profiles update own" on public.profiles for update to authenticated using (id=auth.uid()) with check(id=auth.uid());

drop policy if exists "songs own read" on public.songs;
create policy "songs own read" on public.songs for select to authenticated
using (user_id=auth.uid() or exists(
  select 1 from public.concert_songs cs join public.concert_members cm on cm.concert_id=cs.concert_id
  where cs.song_id=songs.id and cm.user_id=auth.uid()
));
drop policy if exists "songs own write" on public.songs;
create policy "songs own write" on public.songs for all to authenticated
using (user_id=auth.uid()) with check(user_id=auth.uid());

drop policy if exists "concert visible to members" on public.concerts;
create policy "concert visible to members" on public.concerts for select to authenticated
using (owner_id=auth.uid() or exists(select 1 from public.concert_members cm where cm.concert_id=concerts.id and cm.user_id=auth.uid()));
drop policy if exists "concert owner write" on public.concerts;
create policy "concert owner write" on public.concerts for all to authenticated
using (owner_id=auth.uid()) with check(owner_id=auth.uid());

drop policy if exists "members visible" on public.concert_members;
create policy "members visible" on public.concert_members for select to authenticated
using (user_id=auth.uid() or exists(select 1 from public.concerts c where c.id=concert_id and c.owner_id=auth.uid()));
drop policy if exists "members owner manage" on public.concert_members;
create policy "members owner manage" on public.concert_members for all to authenticated
using (exists(select 1 from public.concerts c where c.id=concert_id and c.owner_id=auth.uid()))
with check (exists(select 1 from public.concerts c where c.id=concert_id and c.owner_id=auth.uid()));

drop policy if exists "concert songs visible" on public.concert_songs;
create policy "concert songs visible" on public.concert_songs for select to authenticated
using (exists(select 1 from public.concerts c where c.id=concert_id and (c.owner_id=auth.uid() or exists(select 1 from public.concert_members cm where cm.concert_id=c.id and cm.user_id=auth.uid()))));
drop policy if exists "concert songs owner manage" on public.concert_songs;
create policy "concert songs owner manage" on public.concert_songs for all to authenticated
using (exists(select 1 from public.concerts c where c.id=concert_id and c.owner_id=auth.uid()))
with check (exists(select 1 from public.concerts c where c.id=concert_id and c.owner_id=auth.uid()));

drop policy if exists "live visible to concert" on public.live_sessions;
create policy "live visible to concert" on public.live_sessions for select to authenticated
using (exists(select 1 from public.concerts c where c.id=concert_id and (c.owner_id=auth.uid() or exists(select 1 from public.concert_members cm where cm.concert_id=c.id and cm.user_id=auth.uid()))));
drop policy if exists "live owner host write" on public.live_sessions;
create policy "live owner host write" on public.live_sessions for all to authenticated
using (host_user_id=auth.uid()) with check(host_user_id=auth.uid());

drop policy if exists "backup own" on public.backups;
create policy "backup own" on public.backups for all to authenticated using(user_id=auth.uid()) with check(user_id=auth.uid());

drop policy if exists "history own read" on public.change_history;
create policy "history own read" on public.change_history for select to authenticated using(user_id=auth.uid());
drop policy if exists "history own insert" on public.change_history;
create policy "history own insert" on public.change_history for insert to authenticated with check(user_id=auth.uid());

create or replace function public.share_concert_by_email(p_concert_id text,p_email text,p_role text default 'musician')
returns boolean language plpgsql security definer set search_path=public as $$
declare target_user uuid;
begin
  if not exists(select 1 from public.concerts where id=p_concert_id and owner_id=auth.uid()) then
    raise exception 'No eres propietario de este concierto';
  end if;
  select id into target_user from public.profiles where lower(email)=lower(p_email) limit 1;
  if target_user is null then raise exception 'El usuario todavía no tiene una cuenta LiveVoz'; end if;
  insert into public.concert_members(concert_id,user_id,role)
  values(p_concert_id,target_user,case when p_role in ('operator','musician','singer') then p_role else 'musician' end)
  on conflict(concert_id,user_id) do update set role=excluded.role;
  return true;
end $$;
revoke all on function public.share_concert_by_email(text,text,text) from public;
grant execute on function public.share_concert_by_email(text,text,text) to authenticated;

