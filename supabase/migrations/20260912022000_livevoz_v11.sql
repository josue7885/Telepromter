-- LiveVoz V11.1 Supabase schema
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text unique,
  display_name text,
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.profiles(id,email,display_name)
  values(new.id,new.email,coalesce(new.raw_user_meta_data->>'display_name',split_part(new.email,'@',1)))
  on conflict(id) do update set email=excluded.email;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert or update of email on auth.users
for each row execute function public.handle_new_user();

create table if not exists public.songs (
  id text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  category text not null default 'Personalizada',
  bpm int not null default 100 check (bpm between 30 and 250),
  key text not null default 'C',
  lyrics jsonb not null default '[]'::jsonb,
  chords jsonb not null default '[]'::jsonb,
  cues jsonb not null default '[]'::jsonb,
  transpose_offset int not null default 0,
  updated_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table if not exists public.concerts (
  id text primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  updated_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table if not exists public.concert_members (
  concert_id text not null references public.concerts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'musician' check (role in ('owner','operator','musician','singer')),
  created_at timestamptz not null default now(),
  primary key(concert_id,user_id)
);

create table if not exists public.concert_songs (
  concert_id text not null references public.concerts(id) on delete cascade,
  song_id text not null references public.songs(id) on delete cascade,
  position int not null default 0,
  primary key(concert_id,song_id)
);

create table if not exists public.live_sessions (
  concert_id text primary key references public.concerts(id) on delete cascade,
  host_user_id uuid not null references auth.users(id) on delete cascade,
  state jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.backups (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  payload jsonb not null,
  created_at timestamptz not null default now()
);

create table if not exists public.change_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  action text not null,
  entity_type text not null,
  entity_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_songs_user on public.songs(user_id);
create index if not exists idx_members_user on public.concert_members(user_id);
create index if not exists idx_history_user_created on public.change_history(user_id,created_at desc);
create index if not exists idx_backups_user_created on public.backups(user_id,created_at desc);

